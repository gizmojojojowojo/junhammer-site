"""Regenerate redirects and 410s from data/url_inventory.csv.

Run after editing the inventory:  python3 scripts/build_redirects.py
Writes public/_redirects (301s, read by Cloudflare Pages) and
functions/gone.json (URLs answered with 410 Gone by functions/_middleware.js).
"""
import csv, json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
rows = list(csv.DictReader(open(ROOT / 'data/url_inventory.csv')))
# extra moves introduced by the rebuild (old path -> new path)
EXTRA = {}

final = {}
for r in rows:
    if r['action'] in ('MERGE', 'REDIRECT') and r['target_url']:
        final[r['old_url']] = r['target_url']
final.update(EXTRA)

def resolve(t, depth=0):
    return resolve(final[t], depth + 1) if t in final and depth < 10 else t

gone = sorted(r['old_url'] for r in rows if r['action'] == 'PRUNE-410')
lines = ['# Generated by scripts/build_redirects.py from data/url_inventory.csv. Do not edit by hand.']
wild = []
for src, dst in final.items():
    dst = resolve(dst)
    if src == dst:
        continue
    if src.endswith('*'):
        wild.append(f'{src} {dst} 301')
        continue
    lines.append(f'{src} {dst} 301')
    if src.endswith('/') and src != '/':
        lines.append(f'{src.rstrip("/")} {dst} 301')  # no-trailing-slash variant
lines += wild  # wildcards last so specific rules win
(ROOT / 'public/_redirects').write_text('\n'.join(lines) + '\n')
(ROOT / 'functions').mkdir(exist_ok=True)
(ROOT / 'functions/gone.json').write_text(json.dumps(gone, indent=1) + '\n')
print(f'{len(lines) - 1} redirect rules, {len(gone)} gone URLs')
